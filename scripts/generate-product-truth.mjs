#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const ROOT = new URL('../', import.meta.url);
const DOCS = ['README.md', 'docs/features.md'];
const START = '<!-- product-truth:start -->';
const END = '<!-- product-truth:end -->';
const TAXONOMY_TYPES_START = '<!-- taxonomy-types:start -->';
const TAXONOMY_TYPES_END = '<!-- taxonomy-types:end -->';
const FORMAT_LABELS = {
  csv: 'CSV',
  tsv: 'TSV',
  jsonl: 'JSONL / NDJSON',
  parquet: 'Parquet',
  sqlite: 'SQLite',
  duckdb: 'DuckDB',
  xlsx: 'Excel (.xlsx)',
  arrow: 'Arrow / Feather',
  sav: 'SPSS',
  dta: 'Stata',
  sas7bdat: 'SAS7BDAT',
  xpt: 'SAS XPORT',
  geojson: 'GeoJSON',
  kml: 'KML',
};

async function loadRuntimeRegistries() {
  const built = await build({
    absWorkingDir: new URL('.', ROOT).pathname,
    stdin: {
      contents: `
        export {
          SOURCE_RELEASE_FLAGS,
          SOURCE_GROUPS,
          SOURCE_OPTIONS,
          SUPPORTED_FILE_FORMATS,
        } from './src/core/product-capabilities.ts';
        export { ICEBERG_REST_SUPPORT_PROFILES } from './src/core/iceberg-rest-release.ts';
        export {
          AGENT_ADAPTERS,
          AGENT_BOUNDS,
          AGENT_COMPATIBILITY_VERSIONS,
          AGENT_SCOPES,
        } from './src/core/agent/contract.ts';
        export { SIDECAR_JOB_KINDS } from './src/core/sidecar/types.ts';
        export {
          STANDARDS_PROFILES,
          resolveStandardsCapabilities,
        } from './src/core/standards/capabilities.ts';
      `,
      resolveDir: new URL('.', ROOT).pathname,
      sourcefile: 'product-truth-entry.ts',
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    write: false,
  });
  const js = built.outputFiles?.[0]?.text;
  if (!js) throw new Error('Could not bundle product capability registries.');
  return import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
}

async function taxonomyFacts() {
  const index = JSON.parse(await readFile(new URL('taxonomy/v0.1/index.json', ROOT), 'utf8'));
  const types = (await readFile(new URL('taxonomy/v0.1/types.jsonl', ROOT), 'utf8'))
    .split(/\r?\n/)
    .filter((line) => line.trim().length > 0);
  return { domains: index.domains.length, types: types.length };
}

function renderBlock(registry, taxonomy) {
  const sourceRows = registry.SOURCE_GROUPS.flatMap((group) =>
    registry.SOURCE_OPTIONS.filter((option) => option.group === group.id).map((option) => {
      const readiness =
        option.readiness === 'available'
          ? 'Available'
          : option.readiness === 'advanced'
            ? 'Advanced / BYO'
            : 'Unavailable';
      return `| ${group.label} | ${option.label} | ${readiness} | ${option.hint} |`;
    }),
  );
  const formats = registry.SUPPORTED_FILE_FORMATS.map((id) => FORMAT_LABELS[id] ?? id).join(' · ');
  const jobs = registry.SIDECAR_JOB_KINDS.map((kind) => `\`${kind}\``).join(' · ');
  const scopes = registry.AGENT_SCOPES.map((scope) => `\`${scope}\``).join(' · ');
  const agentAdapters = registry.AGENT_ADAPTERS.map(
    (adapter) => `${adapter.label}: ${adapter.readiness}`,
  ).join(' · ');
  const standards = registry
    .resolveStandardsCapabilities()
    .map((capability) => `${capability.profile}: ${capability.readiness}`)
    .join(' · ');
  const icebergProfiles = registry.ICEBERG_REST_SUPPORT_PROFILES.map(
    (profile) => `${profile.id}: ${profile.readiness}`,
  ).join(' · ');
  return [
    START,
    '<!-- Generated by scripts/generate-product-truth.mjs. Do not edit this block by hand. -->',
    `- **Taxonomy:** ${taxonomy.types} semantic types across ${taxonomy.domains} domains.`,
    `- **Local file formats (${registry.SUPPORTED_FILE_FORMATS.length}):** ${formats}.`,
    `- **Optional sidecar jobs (${registry.SIDECAR_JOB_KINDS.length}):** ${jobs}.`,
    `- **Agent contract:** versions ${registry.AGENT_COMPATIBILITY_VERSIONS.join(' + ')}; scopes ${scopes}; no execution scope; value reads capped at ${registry.AGENT_BOUNDS.queryRows.toLocaleString('en-US')} rows.`,
    `- **Agent adapters:** ${agentAdapters}. Experimental/planned adapters are not release claims.`,
    `- **Standards profiles:** ${standards}. Release-gated profiles are not product availability claims.`,
    `- **Iceberg REST profiles:** ${icebergProfiles}. Release flags: table=${registry.SOURCE_RELEASE_FLAGS.icebergTable}; REST=${registry.SOURCE_RELEASE_FLAGS.icebergRest}. A flag cannot enable an unverified profile.`,
    '- **Build identity:** the app header is injected from the current git release tag and build revision.',
    '',
    '| Group | Choice | Readiness | Boundary |',
    '| --- | --- | --- | --- |',
    ...sourceRows,
    END,
  ].join('\n');
}

function replaceBlock(source, block, path) {
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start < 0 || end < start) {
    throw new Error(`${path} is missing exactly one product-truth marker block.`);
  }
  if (
    source.indexOf(START, start + START.length) >= 0 ||
    source.indexOf(END, end + END.length) >= 0
  ) {
    throw new Error(`${path} contains duplicate product-truth markers.`);
  }
  return `${source.slice(0, start)}${block}${source.slice(end + END.length)}`;
}

function replaceInlineTaxonomyTypes(source, taxonomy, path) {
  const starts = source.split(TAXONOMY_TYPES_START).length - 1;
  const ends = source.split(TAXONOMY_TYPES_END).length - 1;
  if (starts !== 1 || ends !== 1) {
    throw new Error(`${path} is missing exactly one inline taxonomy-types marker pair.`);
  }
  const start = source.indexOf(TAXONOMY_TYPES_START);
  const end = source.indexOf(TAXONOMY_TYPES_END, start + TAXONOMY_TYPES_START.length);
  if (end < start) {
    throw new Error(`${path} has an invalid inline taxonomy-types marker pair.`);
  }
  return `${source.slice(0, start)}${TAXONOMY_TYPES_START}${taxonomy.types}${TAXONOMY_TYPES_END}${source.slice(
    end + TAXONOMY_TYPES_END.length,
  )}`;
}

const check = process.argv.includes('--check');
const registry = await loadRuntimeRegistries();
const taxonomy = await taxonomyFacts();
const block = renderBlock(registry, taxonomy);
let drifted = false;

for (const path of DOCS) {
  const url = new URL(path, ROOT);
  const before = await readFile(url, 'utf8');
  const after = replaceInlineTaxonomyTypes(replaceBlock(before, block, path), taxonomy, path);
  if (before === after) continue;
  drifted = true;
  if (!check) {
    await writeFile(url, after);
    console.log(`[product-truth] updated ${path}`);
  } else {
    console.error(`[product-truth] ${path} is stale; run node scripts/generate-product-truth.mjs`);
  }
}

if (check && drifted) process.exit(1);
if (!drifted) console.log('[product-truth] docs match canonical registries');
